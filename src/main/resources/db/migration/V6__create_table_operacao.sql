CREATE TABLE operacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carteira_id BIGINT NOT NULL,
    acao_id BIGINT NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    quantidade DECIMAL(19,4) NOT NULL,
    preco_unitario DECIMAL(19,4) NOT NULL,
    valor_bruto DECIMAL(19,4) NOT NULL,
    corretagem DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    impostos DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    valor_adicional DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    valor_liquido DECIMAL(19,4) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_operacao_tipo CHECK (tipo IN ('COMPRA', 'VENDA')),
    CONSTRAINT ck_operacao_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_operacao_preco CHECK (preco_unitario > 0),
    CONSTRAINT ck_operacao_corretagem CHECK (corretagem >= 0),
    CONSTRAINT ck_operacao_impostos CHECK (impostos >= 0),
    CONSTRAINT ck_operacao_valor_adicional CHECK (valor_adicional >= 0),
    CONSTRAINT fk_operacao_carteira FOREIGN KEY (carteira_id) REFERENCES carteira (id),
    CONSTRAINT fk_operacao_acao FOREIGN KEY (acao_id) REFERENCES acao (id)
);
